"""Evaluation as code: golden methods and finding reviews, scored against any analysis.json.

Verdicts are human judgments recorded in YAML (evals/). This module makes them
cheap to produce and reproducible to score: `review_sheet` puts every golden
method's description next to its source, and the summaries count recorded
verdicts per model. Nothing here calls an LLM.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from codebase_analyzer.errors import ConfigError
from codebase_analyzer.schema.output import AnalysisOutput, MethodOut

DESCRIPTION_VERDICTS = ("correct", "partially_correct", "incorrect")
FINDING_CATEGORIES = ("valid_bug", "valid_improvement", "style_opinion", "false_positive")


@dataclass(frozen=True)
class GoldenMethod:
    file: str  # repo-relative path
    method: str
    line: int  # first line of the declaration, as in the analysis
    verdicts: dict[str, dict[str, str]] = field(default_factory=dict)  # model -> {verdict, note}


def _check(value: str, allowed: tuple[str, ...], where: str) -> None:
    if value not in allowed:
        raise ConfigError(f"{where}: {value!r} is not one of {', '.join(allowed)}")


def load_golden(path: Path) -> tuple[dict[str, str], list[GoldenMethod]]:
    data: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
    methods = []
    for m in data["methods"]:
        golden = GoldenMethod(m["file"], m["method"], int(m["line"]), m.get("verdicts") or {})
        for model, v in golden.verdicts.items():
            _check(v["verdict"], DESCRIPTION_VERDICTS, f"{path}: {golden.method} / {model}")
        methods.append(golden)
    return data["rubric"], methods


def load_finding_reviews(path: Path) -> dict[str, list[dict[str, str]]]:
    """model -> reviewed findings ({scope, title, category, note})."""
    data: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
    reviews: dict[str, list[dict[str, str]]] = {m: r["findings"] for m, r in data["models"].items()}
    for model, findings in reviews.items():
        for f in findings:
            _check(f["category"], FINDING_CATEGORIES, f"{path}: {model} / {f['title']}")
    return reviews


def find_method(analysis: AnalysisOutput, golden: GoldenMethod) -> tuple[str, MethodOut] | None:
    for c in analysis.classes:
        if c.file == golden.file:
            for m in c.methods:
                if m.name == golden.method and m.line_start == golden.line:
                    return c.fqn, m
    return None


def description_scores(golden: list[GoldenMethod], model: str) -> Counter[str]:
    return Counter(g.verdicts[model]["verdict"] for g in golden if model in g.verdicts)


def finding_scores(reviews: list[dict[str, str]]) -> Counter[str]:
    return Counter(f["category"] for f in reviews)


def unmatched_reviews(analysis: AnalysisOutput, reviews: list[dict[str, str]]) -> list[str]:
    """Reviewed findings that are not in this analysis (keeps the record honest)."""
    present = {(f.scope, f.title) for f in analysis.findings}
    return [f"{r['scope']}: {r['title']}" for r in reviews if (r["scope"], r["title"]) not in present]


def review_sheet(analysis: AnalysisOutput, rubric: dict[str, str], golden: list[GoldenMethod], repo: Path) -> str:
    model = analysis.metadata.model
    out = [
        f"# Description review: {model}",
        "",
        f"Generated by `codebase-analyzer eval` from `analysis.json` (commit {(analysis.metadata.commit_sha or '?')[:7]}). "
        "Each description is shown next to the source it describes; verdicts live in `evals/golden_methods.yaml`.",
        "",
        "Rubric:",
        "",
    ]
    out += [f"- **{name}**: {text}" for name, text in rubric.items()]
    for i, g in enumerate(golden, start=1):
        found = find_method(analysis, g)
        out += ["", f"## {i}. `{g.method}` ({g.file}:{g.line})", ""]
        if found is None:
            out.append("_Not found in this analysis (file or line changed)._")
            continue
        fqn, m = found
        recorded = g.verdicts.get(model)
        source = (repo / g.file).read_text(encoding="utf-8").splitlines()[m.line_start - 1 : m.line_end]
        out += [
            f"Class `{fqn}`, lines {m.line_start}-{m.line_end}, cyclomatic complexity "
            f"{m.complexity.cyclomatic if m.complexity else 'n/a'}.",
            "",
            f"**Description** ({m.description_source}): {m.description or '_none_'}",
            "",
            "**Verdict:** "
            + (f"{recorded['verdict']}: {recorded.get('note', '')}" if recorded else "_not reviewed for this model_"),
            "",
            "```java",
            *source,
            "```",
        ]
    scores = description_scores(golden, model)
    if scores:
        out += [
            "",
            "## Score",
            "",
            ", ".join(f"{v}: {scores.get(v, 0)}" for v in DESCRIPTION_VERDICTS) + f" (of {len(golden)})",
        ]
    return "\n".join(out) + "\n"
