"""Rule-based descriptions and framework notes (no LLM).

1. Trivial members: simple getters/setters, empty bodies, field-assigning
   constructors, one-line delegations and toString/equals/hashCode. They get a
   templated description and `trivial: true`.
2. Abstract members whose behaviour is defined elsewhere: MapStruct mapper
   methods, Spring Data derived queries, and interface methods implemented by a
   project class. They get a templated, factual description.
3. Framework notes: behaviour generated by Lombok / MapStruct or inherited from
   Spring Data, recorded instead of inventing the generated methods.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from codebase_analyzer.analysis.java_parser import JavaFile, Member, TypeDecl

_GETTER = re.compile(r"^\{\s*return\s+(?:this\.)?(\w+)\s*;\s*\}$")
_SETTER = re.compile(r"^\{\s*(?:this\.)?(\w+)\s*=\s*(\w+)\s*;\s*\}$")
_ASSIGN = re.compile(r"(?:this\.)?(\w+)\s*=\s*(\w+)\s*;")
_DELEGATE = re.compile(r"^\{\s*(?:return\s+)?((?:this\.)?\w+(?:\.\w+)*)\.(\w+)\(([^()]*)\)\s*;\s*\}$")
_DERIVED_QUERY = re.compile(r"^(find|read|get|query|search|stream|count|exists|delete|remove)\w*By[A-Z]\w*$")

SPRING_DATA_BASES = {
    "Repository",
    "CrudRepository",
    "ListCrudRepository",
    "PagingAndSortingRepository",
    "ListPagingAndSortingRepository",
    "JpaRepository",
    "QuerydslPredicateExecutor",
    "JpaSpecificationExecutor",
}
LOMBOK_NOTES = {
    "Getter": "Lombok @Getter generates getter methods for the fields.",
    "Setter": "Lombok @Setter generates setter methods for the fields.",
    "Data": "Lombok @Data generates getters, setters, equals/hashCode, toString and a required-args constructor.",
    "Value": "Lombok @Value makes the class immutable and generates getters, equals/hashCode and toString.",
    "Builder": "Lombok @Builder generates a builder (static builder() method).",
    "NoArgsConstructor": "Lombok @NoArgsConstructor generates a no-argument constructor.",
    "AllArgsConstructor": "Lombok @AllArgsConstructor generates a constructor taking every field.",
    "RequiredArgsConstructor": "Lombok @RequiredArgsConstructor generates a constructor for final and @NonNull fields.",
    "ToString": "Lombok @ToString generates toString().",
    "EqualsAndHashCode": "Lombok @EqualsAndHashCode generates equals() and hashCode().",
    "FieldNameConstants": "Lombok @FieldNameConstants generates a nested Fields class with field-name constants.",
    "Slf4j": "Lombok @Slf4j generates a static SLF4J `log` field.",
}


@dataclass(frozen=True)
class DeterministicDescription:
    description: str
    trivial: bool


def _strip_generics(type_name: str) -> str:
    return type_name.split("<", 1)[0].rsplit(".", 1)[-1].strip()


def _param_names(member: Member) -> set[str]:
    return {p.name for p in member.parameters}


def describe_trivial(member: Member, owner: TypeDecl) -> DeterministicDescription | None:
    """Return a templated description if the member is trivial, else None."""
    if member.body is None:
        return None
    body = " ".join(member.body.split())
    n_params = len(member.parameters)

    if member.name == "toString" and n_params == 0:
        return DeterministicDescription("Overrides Object.toString().", True)
    if member.name == "hashCode" and n_params == 0:
        return DeterministicDescription("Overrides Object.hashCode().", True)
    if member.name == "equals" and n_params == 1:
        return DeterministicDescription("Overrides Object.equals(Object) with field-based equality.", True)
    if re.fullmatch(r"\{\s*\}", body):
        what = "constructor" if member.kind == "constructor" else "method"
        return DeterministicDescription(f"Empty {what} body.", True)

    if member.kind == "constructor":
        if c := re.fullmatch(r"\{\s*(super|this)\s*\((.*)\)\s*;\s*\}", body):
            target = "superclass" if c.group(1) == "super" else "another"
            return DeterministicDescription(f"Delegates to {target} constructor: `{c.group(1)}({c.group(2)})`.", True)
        statements = [s for s in body.strip("{} ").split(";") if s.strip()]
        assigns = [a for s in statements if (a := _ASSIGN.fullmatch(s.strip() + ";"))]
        if statements and len(assigns) == len(statements) and all(a.group(2) in _param_names(member) for a in assigns):
            fields = ", ".join(a.group(1) for a in assigns)
            return DeterministicDescription(f"Initializes fields ({fields}) from constructor parameters.", True)
        return None

    if n_params == 0 and re.match(r"(get|is)[A-Z]", member.name) and (g := _GETTER.match(body)):
        return DeterministicDescription(f"Returns the `{g.group(1)}` field.", True)
    if (
        n_params == 1
        and re.match(r"set[A-Z]", member.name)
        and (s := _SETTER.match(body))
        and s.group(2) == member.parameters[0].name
    ):
        return DeterministicDescription(f"Sets the `{s.group(1)}` field.", True)
    if d := _DELEGATE.match(body):
        # Only delegation to an injected collaborator (a final field) passing the
        # method's own parameters through counts; `name.toUpperCase()` does not.
        receiver = d.group(1).removeprefix("this.")
        collaborators = {f.name for f in owner.fields if "final" in f.modifiers and "static" not in f.modifiers}
        args = [a.strip() for a in d.group(3).split(",") if a.strip()]
        if receiver in collaborators and all(a in _param_names(member) for a in args):
            return DeterministicDescription(
                f"Delegates to `{d.group(1)}.{d.group(2)}(...)` with its own arguments.", True
            )
    return None


def describe_abstract(
    member: Member, owner: TypeDecl, implementations: dict[str, list[TypeDecl]]
) -> DeterministicDescription | None:
    """Templated description for abstract members whose behaviour is defined elsewhere."""
    if member.body is not None:
        return None
    if owner.kind == "annotation":
        return DeterministicDescription("Annotation element.", False)
    if any(a.name == "Mapper" for a in owner.annotations):
        sources = ", ".join(p.type for p in member.parameters) or "nothing"
        return DeterministicDescription(
            f"MapStruct mapping method ({sources} -> {member.return_type}); implementation is generated at build time.",
            False,
        )
    if _DERIVED_QUERY.match(member.name) and _extends_spring_data(owner):
        return DeterministicDescription(
            "Spring Data derived query method; the query is generated from the method name.", False
        )
    for impl in implementations.get(owner.name, []):
        if any(
            m.name == member.name and len(m.parameters) == len(member.parameters) and m.body is not None
            for m in impl.members
        ):
            return DeterministicDescription(
                f"Abstract declaration; implemented by {impl.name}.{member.name} (see that entry).", False
            )
    return None


def _extends_spring_data(decl: TypeDecl) -> bool:
    return any(_strip_generics(t) in SPRING_DATA_BASES for t in decl.extends + decl.implements)


def framework_notes(decl: TypeDecl, jf: JavaFile) -> list[str]:
    notes = [LOMBOK_NOTES[a.name] for a in decl.annotations if a.name in LOMBOK_NOTES]
    names = {a.name for a in decl.annotations}
    if "Mapper" in names:
        notes.append(
            "MapStruct @Mapper: an implementation class is generated at build time; abstract methods are generated mappings."
        )
    if "Entity" in names:
        table = next((a for a in decl.annotations if a.name == "Table"), None)
        table_name = table.arguments.get("name") if table else None
        notes.append(f"JPA entity{f' mapped to table {table_name}' if table_name else ''}.")
    inherited = [t for t in decl.extends + decl.implements if _strip_generics(t) in SPRING_DATA_BASES]
    if inherited:
        notes.append(
            f"Spring Data repository: inherits query/CRUD methods from {', '.join(inherited)}; inherited methods are not listed."
        )
    for t in decl.extends:
        base = _strip_generics(t)
        if base == "RepresentationModelAssemblerSupport":
            notes.append(
                "Spring HATEOAS assembler: inherits toModel/toCollectionModel support from RepresentationModelAssemblerSupport."
            )
        elif base == "RepresentationModel":
            notes.append("Spring HATEOAS representation model: carries hypermedia links.")
    if any(i.startswith("com.querydsl") for i in jf.imports) and decl in jf.types:
        notes.append(
            "Builds type-safe queries with Querydsl; Q-classes are generated at build time and are not in the repository."
        )
    if any(i.startswith("com.blazebit") for i in jf.imports) and decl in jf.types:
        notes.append("Uses Blaze-Persistence query extensions on top of Querydsl/JPA.")
    return notes


def implementations_index(types: list[TypeDecl]) -> dict[str, list[TypeDecl]]:
    """Map interface simple name -> project types that implement it."""
    index: dict[str, list[TypeDecl]] = {}
    for t in types:
        for iface in t.implements:
            index.setdefault(_strip_generics(iface), []).append(t)
    return index
